def _acquire_geometry():
    """Build (gm, beams, loader) from the selected input mode."""
    loader = None
    if input_mode == "Import CAD (DXF)":
        if cad_file is None:
            st.error("Please upload a DXF file.")
            st.stop()
        header = cad_file.getvalue()[:100]
        if not (b"AutoCAD" in header or b"SECTION" in header or b"  0" in header or b"999" in header):
            st.error("Invalid DXF file. Security check failed: Magic bytes do not match expected DXF format.")
            st.stop()
        tmp = tempfile.NamedTemporaryFile(suffix='.dxf', delete=False)
        tmp.write(cad_file.getbuffer())
        tmp.close()
        from src.cad_loader import CADLoader
        try:
            loader = CADLoader(tmp.name)
            gm, beams = loader.load_grid_manager(auto_frame=auto_frame, seismic_zone=seismic_zone,
                                                 story_height_m=story_height, num_stories=num_stories)
            st.session_state['arch_walls'] = loader.get_architectural_walls()
            st.session_state['cad_warnings'] = list(loader.placement_warnings) + list(loader.load_warnings)
            gm.columns = gm.stack_columns([c for c in gm.columns if c.level == 0], num_stories, story_height)
        except Exception as e:
            logger.error("Failed to load CAD file: %s", e)
            capture_exception(e)
            st.error(f"Failed to load CAD: {e}")
            st.stop()
        finally:
            try:
                os.unlink(tmp.name)
            except OSError:
                pass
    elif input_mode == "Import BIM (IFC)":
        if ifc_file is None:
            st.error("Please upload an IFC file.")
            st.stop()
        if b"ISO-10303-21" not in ifc_file.getvalue()[:100]:
            st.error("Invalid IFC file. Security check failed: Missing ISO-10303-21 STEP signature.")
            st.stop()
        tmp = tempfile.NamedTemporaryFile(suffix='.ifc', delete=False)
        tmp.write(ifc_file.getbuffer())
        tmp.close()
        from src.bim_loader import BIMLoader
        try:
            loader = BIMLoader(tmp.name)
            gm, beams = loader.load_grid_manager()
            st.session_state['cad_warnings'] = list(loader.warnings)
        except Exception as e:
            logger.error("Failed to load IFC file: %s", e)
            capture_exception(e)
            st.error(f"Failed to load IFC: {e}")
            st.stop()
        finally:
            try:
                os.unlink(tmp.name)
            except OSError:
                pass
    else:
        gm = GridManager(width_m=width, length_m=length, num_stories=num_stories, story_height_m=story_height)
        gm.cantilever_dirs = cant_dirs
        gm.cantilever_len_m = 1.5
        gm.generate_grid()
        beams = gm.generate_beams()
        st.session_state['cad_warnings'] = []
    return gm, beams, loader


